const byKind: Record<IdeaKind, Icon> = {
  favor: GiftIcon, gift: GiftIcon, mother: FlowerLotusIcon, decor: SparkleIcon, sign: SignpostIcon, hosp: CoffeeIcon,
  photo: CameraIcon, hospital: HeartIcon, aqiqah: StarAndCrescentIcon, keepsake: TreasureChestIcon, thanks: HandHeartIcon,
};

export function ideaIcon(x: Pick<AnyIdea, "en" | "kind">): { icon: Icon; matched: boolean } {
  for (const [re, I] of rules) if (re.test(x.en)) return { icon: I, matched: true };
  return { icon: byKind[x.kind], matched: false };
}

const tones = ["#e8a5b5", "#a9c1dc", "#c9b8e0", "#efd28f", "#bcd3b3", "#f2a07b", "#7fb8e6", "#d9b38c", "#5fb9a0", "#d96aa4", "#9cb59a", "#f3b07a"];
function hash(s: string) {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 16777619);
  return h >>> 0;
}

/** The idea, drawn: its own icon on a soft tile, with a little pattern so each tile is its own. */
export function IdeaArt({ idea, className = "", size = 30 }: { idea: Pick<AnyIdea, "en" | "kind">; className?: string; size?: number }) {
  const h = hash(idea.en);
  const c = tones[h % tones.length];
  const I = ideaIcon(idea).icon;
  const shape = (h >> 4) % 3;
  return (
    <span aria-hidden="true" className={`relative grid shrink-0 place-items-center overflow-hidden rounded-[16px] ${className}`} style={{ background: `linear-gradient(${(h >> 8) % 360}deg, color-mix(in oklab, ${c} 28%, #fff), color-mix(in oklab, ${c} 12%, #fff))`, color: `color-mix(in oklab, ${c} 62%, #3f3b52)` }}>
      {shape === 0 && <span className="absolute -end-3 -top-3 size-1/2 rounded-full" style={{ background: `color-mix(in oklab, ${c} 30%, #fff)` }} />}
      {shape === 1 && <span className="absolute -bottom-4 -start-2 size-2/3 rounded-full" style={{ background: `color-mix(in oklab, ${c} 22%, #fff)` }} />}
      {shape === 2 && <span className="absolute inset-x-0 bottom-0 h-1/3" style={{ background: `color-mix(in oklab, ${c} 18%, #fff)` }} />}
      <I size={size} weight="duotone" className="relative" />
    </span>
  );
}
