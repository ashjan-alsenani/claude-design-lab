// Lists the AI sample photos in public/brand/qudoom/{favors,kinds,looks} into a typed module, so a
// photo shows up as soon as its file exists (and nothing points at a missing file).
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const dir = (d) => {
  const p = path.join(root, "public/brand/qudoom", d);
  return fs.existsSync(p) ? fs.readdirSync(p).filter((f) => f.endsWith(".webp")).sort() : [];
};
const map = (d) => Object.fromEntries(dir(d).map((f) => [f.replace(/\.webp$/, ""), `/brand/qudoom/${d}/${f}`]));
const out = `// Generated by scripts/qudoom-photos.mjs. Do not edit by hand.
export const favorPhotoFiles: Record<string, string> = ${JSON.stringify(map("favors"), null, 2)};
export const kindPhotoFiles: Record<string, string> = ${JSON.stringify(map("kinds"), null, 2)};
export const lookPhotoFiles: Record<string, string> = ${JSON.stringify(map("looks"), null, 2)};
/** One photo per idea, keyed by ideaKey (a hash of the English text, stable when ideas are added). */
export const ideaPhotoFiles: Record<string, string> = ${JSON.stringify(map("ideas"))};
`;
fs.writeFileSync(path.join(root, "src/products/qudoom/ui/photos.gen.ts"), out);
console.log("photos:", dir("favors").length, dir("kinds").length, dir("looks").length, dir("ideas").length);
