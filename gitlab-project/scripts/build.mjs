// Builds the deployable site into dist/ (and, with --single, one self-contained HTML file into dist-single/).
// Usage: node scripts/build.mjs [--single]
import {cpSync, rmSync, mkdirSync, writeFileSync, readFileSync, readdirSync, statSync} from 'node:fs';
import {join, extname} from 'node:path';
import {execSync} from 'node:child_process';
import {ROOT, loadEnv, appConfig} from './env.mjs';

const env = loadEnv();
const cfg = appConfig(env);
const SRC = join(ROOT, 'src');
const DIST = join(ROOT, 'dist');

// Build id: CI commit when available, else git, else a timestamp. Used to refresh the offline cache on every release.
let buildId = env.CI_COMMIT_SHORT_SHA || env.BUILD_ID || '';
if (!buildId) { try { buildId = execSync('git rev-parse --short HEAD', {cwd: ROOT, stdio: ['ignore', 'pipe', 'ignore']}).toString().trim(); } catch {} }
if (!buildId) buildId = Date.now().toString(36);

rmSync(DIST, {recursive: true, force: true});
cpSync(SRC, DIST, {recursive: true});

const configJs = `/* Generated by scripts/build.mjs from environment settings. Do not edit by hand. */\nwindow.DTD_CONFIG = ${JSON.stringify(cfg, null, 2)};\n`;
writeFileSync(join(DIST, 'config.js'), configJs);

const sw = readFileSync(join(DIST, 'sw.js'), 'utf8').replace('__BUILD_ID__', buildId);
writeFileSync(join(DIST, 'sw.js'), sw);

const warnings = [];
if (!cfg.ownerUsername || !/^[0-9a-f]{64}$/.test(cfg.ownerPasswordSha256)) warnings.push('OWNER_USERNAME / OWNER_PASSWORD_SHA256 are not set: the owner (administrator) account cannot sign in. Run "npm run hash-password" and put the result in .env or a CI/CD variable.');

const size = dir => readdirSync(dir).reduce((n, f) => { const p = join(dir, f); const s = statSync(p); return n + (s.isDirectory() ? size(p) : s.size); }, 0);
console.log(`Built dist/ (build ${buildId}, ${(size(DIST) / 1048576).toFixed(1)} MB)`);

if (process.argv.includes('--single')) {
  // One HTML file with fonts, icons, tour images, settings and code inlined. Opens straight from disk.
  const mime = {'.woff2': 'font/woff2', '.png': 'image/png', '.jpg': 'image/jpeg', '.svg': 'image/svg+xml'};
  const b64 = p => `data:${mime[extname(p)] || 'application/octet-stream'};base64,${readFileSync(p).toString('base64')}`;
  let css = readFileSync(join(DIST, 'assets/styles.css'), 'utf8');
  for (const u of new Set(css.match(/url\((fonts\/[^)]+)\)/g) || [])) css = css.split(u).join(`url(${b64(join(DIST, 'assets', u.slice(4, -1)))})`);
  let js = readFileSync(join(DIST, 'assets/app.js'), 'utf8');
  for (const q of new Set(js.match(/"assets\/tour\/(?:en\/)?[a-z]+\.jpg"/g) || [])) js = js.split(q).join(`"${b64(join(DIST, q.slice(1, -1)))}"`);
  const esc = t => t.replace(/<\/script/gi, '<\\/script');
  let html = readFileSync(join(DIST, 'index.html'), 'utf8')
    .replace('<link rel="manifest" href="manifest.webmanifest">\n', '')
    .replace('href="assets/icons/icon-192.png"', `href="${b64(join(DIST, 'assets/icons/icon-192.png'))}"`)
    .replace('href="assets/icons/apple-touch-icon.png"', `href="${b64(join(DIST, 'assets/icons/apple-touch-icon.png'))}"`)
    .replace('<script src="assets/boot.js"></script>', () => `<script>\n${esc(readFileSync(join(DIST, 'assets/boot.js'), 'utf8'))}</script>`)
    .replace('<link rel="stylesheet" href="assets/styles.css">', () => `<style>\n${css}\n</style>`)
    .replace('<script src="config.js"></script>', () => `<script>\n${esc(configJs)}</script>`)
    .replace('<script src="assets/app.js"></script>', () => `<script>\n${esc(js)}\n</script>`)
    .replace('<script src="assets/sw-register.js"></script>\n', '');
  for (const tag of ['src="assets/boot.js"', 'src="config.js"', 'src="assets/app.js"', 'href="assets/styles.css"']) if (html.includes(tag)) throw new Error(`single-file build: ${tag} was not inlined`);
  const out = join(ROOT, 'dist-single');
  rmSync(out, {recursive: true, force: true}); mkdirSync(out);
  writeFileSync(join(out, 'employee-directory.html'), html);
  console.log(`Built dist-single/employee-directory.html (${(html.length / 1048576).toFixed(1)} MB)`);
}

for (const w of warnings) console.warn('WARNING: ' + w);
if (warnings.length && env.REQUIRE_OWNER === 'true') { console.error('REQUIRE_OWNER=true and owner settings are missing; failing the build.'); process.exit(1); }
