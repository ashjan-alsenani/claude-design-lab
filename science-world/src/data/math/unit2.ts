/** Cells of a ring: a square of side `side` centred in an n×n grid, minus the centred square of side `side − 2`. */
function square(n: number, side: number, color: string) {
  const o = (n - side) / 2;
  const cells: { x: number; y: number; color: string }[] = [];
  for (let x = o; x < o + side; x++)
    for (let y = o; y < o + side; y++) {
      const inner = x > o && x < o + side - 1 && y > o && y < o + side - 1;
      if (!inner) cells.push({ x, y, color });
    }
  return cells;
}

